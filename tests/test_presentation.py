def _finding(title, severity, steps=None):
    return {"title": title, "subsystem": "storage", "severity": severity,
            "evidence": [{"line": 1, "quote": "q", "verified": True}],
            "next_steps": steps or [f"fix {title}"]}


def _result(*findings, inconclusive=0):
    return {"summary": "s", "findings": list(findings),
            "inconclusive_concerns": [
                {"title": f"open {i}", "verification_question": f"check {i}"}
                for i in range(inconclusive)],
            "dismissed_concerns": []}


def test_health_levels():
    assert build_verdict(_result(_finding("a", "critical")), VerifySummary())["health"] == "CRITICAL"
    assert build_verdict(_result(_finding("a", "high")), VerifySummary())["health"] == "WARNING"
    assert build_verdict(_result(_finding("a", "medium")), VerifySummary())["health"] == "ATTENTION"
    assert build_verdict(_result(), VerifySummary())["health"] == "OK"
    assert build_verdict(_result(inconclusive=1), VerifySummary())["health"] == "UNKNOWN"
    assert build_verdict(None, VerifySummary())["health"] == "NO DATA"


def test_data_loss_headline():
    f = _finding("disk dying", "critical")
    f["severity_explanation"] = "journal abort, potential data loss"
    v = build_verdict(_result(f), VerifySummary())
    assert "data-loss risk" in v["headline"]


def test_actions_sorted_deduped_capped():
    r = _result(
        _finding("low", "low", ["shared fix", "low fix"]),
        _finding("crit", "critical", ["shared fix", "crit fix", "crit fix 2"]),
        _finding("high", "high", ["high fix"]),
    )
    actions = collect_actions(r, limit=4)
    assert actions[0] == "shared fix"           # critical finding first
    assert actions.count("shared fix") == 1
    assert len(actions) <= 4


def test_actions_fall_back_to_questions():
    r = _result(inconclusive=2)
    actions = collect_actions(r)
    assert actions and actions[0].startswith("Verify:")


def test_verdict_box_and_render():
    r = _result(_finding("sda link failure", "critical"))
    summary = VerifySummary(total=1, passed=1)
    box = render_verdict_box(build_verdict(r, summary))
    assert "HEALTH: CRITICAL" in box and "DO NOW" in box and "evidence 1/1" in box
    report = render(r, RawBundle(dmesg_text=""), summary, [Block(1, 1, ["io-error"])],
                    changes_text="### $ uptime\nboot time")
    assert report.index("HEALTH:") < report.index("## Overall conclusion")
    assert "Appendix: system changes around the fault" in report
    assert "Generated by dmesg-agent v" in report


def test_render_brief_is_compact():
    r = _result(_finding("sda link failure", "critical"))
    brief = render_brief(r, RawBundle(dmesg_text=""), VerifySummary(total=1, passed=1))
    assert "HEALTH: CRITICAL" in brief
    assert "| # | Severity | Issue |" in brief
    assert "Appendix:" not in brief
    assert "Root-cause hypothesis" not in brief


def test_ansi_color():
    colored = apply_ansi("HEALTH: CRITICAL\n🔴 critical x\n## Heading")
    assert "\x1b[1;31m" in colored and "\x1b[0m" in colored
    assert "\x1b[1m## Heading" in colored


def test_render_includes_case_diff():
    r = _result(_finding("sda link failure", "critical"))
    r["knowledge"] = {"host": "h", "new_cases": 0, "recurrences": 1, "matches": [{
        "finding_index": 0, "title": "sda link failure", "case_id": 1, "tier": "exact",
        "status": "confirmed", "occurrences": 2, "first_seen": "2026-11-25T00:00:00Z"}],
        "diff": {"new": [{"title": "new one"}], "resolved": [], "ongoing": [{"title": "sda"}]}}
    report = render(r, RawBundle(dmesg_text=""), VerifySummary(), [Block(1, 1, ["x"])])
    assert "Since the previous run" in report
    assert "1 new" in report and "1 ongoing" in report


def test_html_report_escapes_and_shows_verdict():
    r = _result(_finding("<script>alert(1)</script>", "critical"))
    html = render_html(r, RawBundle(dmesg_text="", kernel_version="6.12", source="test"),
                       VerifySummary(total=1, passed=1), [Block(1, 2, ["io-error"])],
                       ["[1.0] first", "[2.0] second"], changes_text="changes")
    assert '<div class="banner critical">' in html
    assert "HEALTH: CRITICAL" in html
    assert "&lt;script&gt;" in html and "<script>alert" not in html
    assert "Timeline of suspicious segments" in html
    assert "Appendix: system changes" in html
    assert "Generated by dmesg-agent" in html


def test_parse_first_error_time_dmesg_t():
    lines = ["[    0.0] boot ok", "[Wed Nov 25 21:59:49 2026] ata6: SError: { CommWake }"]
    ts = parse_first_error_time(lines, [Block(2, 2, ["ata"])])
    assert ts == datetime(2026, 11, 25, 21, 59, 49)


def test_parse_first_error_time_journalctl_and_rollover():
    lines = ["Nov 25 21:59:49 debian kernel: nvme: timeout"]
    assert parse_first_error_time(lines, [Block(1, 1, ["nvme"])],
                                  now=datetime(2026, 11, 27)) == datetime(2026, 11, 25, 21, 59, 49)
    lines = ["Dec 31 23:00:00 debian kernel: oops"]
    assert parse_first_error_time(lines, [Block(1, 1, ["bug"])],
                                  now=datetime(2026, 1, 2)) == datetime(2025, 12, 31, 23, 0, 0)


def test_parse_first_error_time_raw_monotonic_returns_none():
    lines = ["[   12.789012] Out of memory: Killed process 1 (x)"]
    assert parse_first_error_time(lines, [Block(1, 1, ["oom"])]) is None


class _RecExecutor:
    name, can_collect = "rec", True

    def __init__(self):
        self.runs = []

    def run(self, cmd, sudo=False, timeout=30):
        self.runs.append((cmd, sudo))
        return ExecResult(ok=True, out="sample output")

    def close(self):
        pass


def test_system_changes_window_and_static_commands():
    ex = _RecExecutor()
    evs = run_system_changes(ex, datetime(2026, 11, 25, 21, 59, 49))
    cmds = [c for c, _sudo in ex.runs]
    assert any("--since '2026-11-25 21:49:49'" in c and "--until '2026-11-25 22:04:49'" in c
               for c in cmds)
    assert any("vmlinuz-$(uname -r)" in c for c in cmds)
    assert any("apt/history.log" in c for c in cmds)
    assert all(not sudo for _c, sudo in ex.runs)
    assert all(e.status == "ok" for e in evs)


def test_system_changes_without_timestamp_skips_window():
    ex = _RecExecutor()
    run_system_changes(ex, None)
    assert not any("--since '20" in c for c, _ in ex.runs)
    assert any("last -x" in c for c, _ in ex.runs)
